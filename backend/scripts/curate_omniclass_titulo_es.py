def apply_replacements(text: str) -> str:
    result = text
    for source, target in PHRASE_REPLACEMENTS:
        result = result.replace(source, target)
    for source, target in WORD_REPLACEMENTS:
        result = re.sub(rf"\b{re.escape(source)}\b", target, result)
    result = re.sub(r"\s{2,}", " ", result).strip()
    return result


def main():
    conn = psycopg2.connect(
        dbname=DB_NAME,
        user=DB_USER,
        password=DB_PASS,
        host=DB_HOST,
        port=DB_PORT,
    )
    conn.autocommit = False
    cur = conn.cursor()
    updated = 0
    try:
        cur.execute("SELECT id, titulo_es FROM omniclass_maestro WHERE titulo_es IS NOT NULL")
        rows = cur.fetchall()
        for row_id, titulo_es in rows:
            translated = apply_replacements(titulo_es or "")
            if translated != (titulo_es or ""):
                cur.execute(
                    "UPDATE omniclass_maestro SET titulo_es = %s WHERE id = %s",
                    (translated, row_id),
                )
                updated += 1
        conn.commit()
        print(f"OmniClass titulo_es curated rows: {updated}")
    except Exception:
        conn.rollback()
        raise
    finally:
        cur.close()
        conn.close()


